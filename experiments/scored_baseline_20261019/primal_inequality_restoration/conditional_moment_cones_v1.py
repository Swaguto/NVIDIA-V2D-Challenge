"""Research continuous PSD separation, with exact rational square certificates.

Each separating plane is generated by a polynomial square, or t(1-t) times
a square, conditional on nonnegative Bernstein weights of the other variables.
Eigenvectors supply polynomial coefficients only. They are never robot poses.
No actual input weights are clipped or normalized, including signed returns.
"""
from fractions import Fraction as F
from itertools import product,combinations
from math import comb
import hashlib,json,math

def rec(v):
    v=F(v);return dict(numerator_hex=hex(v.numerator),denominator_hex=hex(v.denominator),approx=float(v))
def dec(v):return F(int(v['numerator_hex'],16),int(v['denominator_hex'],16))
def groups(columns):
    tables={}
    for i,col in enumerate(columns):
        scope=tuple(col['scope']);index=tuple(col['index'])
        if not scope or len(set(scope))!=len(scope)or len(scope)!=len(index)or any(type(k)is not int or not 0<=k<=4 for k in index)or index in tables.setdefault(scope,{}):raise ValueError('malformed or duplicate table entry')
        tables[scope][index]=i
    result=[]
    for scope,table in tables.items():
        if set(table)!=set(product(range(5),repeat=len(scope))):raise ValueError('complete degree4 tables required')
        for axis in range(len(scope)):
            others=[i for i in range(len(scope))if i!=axis]
            for other in product(range(5),repeat=len(others)):
                selected={k[axis]:v for k,v in table.items()if tuple(k[a]for a in others)==other}
                result.append(dict(id=len(result),scope=list(scope),axis=axis,conditioning_index=list(other),columns=[selected[k]for k in range(5)]))
    return result
def moments(weights):
    if len(weights)!=5:raise ValueError('five degree4 Bernstein weights required')
    w=list(map(F,weights))
    return [sum((F(comb(k,r),comb(4,r))if k>=r else F(0))*v for k,v in enumerate(w))for r in range(5)]
def matrices(y):
    if len(y)!=5:raise ValueError('five moments required')
    return dict(Hankel=[[y[i+k]for k in range(3)]for i in range(3)],localizer=[[y[i+k+1]-y[i+k+2]for k in range(2)]for i in range(2)])
def determinant(A):
    if len(A)==1:return A[0][0]
    return sum((-1)**k*A[0][k]*determinant([r[:k]+r[k+1:]for r in A[1:]])for k in range(len(A)))
def principal_minors(A):
    return [dict(indices=list(s),value=rec(determinant([[A[i][k]for k in s]for i in s])))for n in range(1,len(A)+1)for s in combinations(range(len(A)),n)]
def square_coefficients(vector,kind):
    if kind not in['Hankel','localizer']or len(vector)!=(3 if kind=='Hankel'else 2):raise ValueError('invalid cone/vector shape')
    p={}
    for i,a in enumerate(vector):
        for k,b in enumerate(vector):p[i+k]=p.get(i+k,F(0))+F(a)*F(b)
    if kind=='localizer':
        q={}
        for k,v in p.items():q[k+1]=q.get(k+1,F(0))+v;q[k+2]=q.get(k+2,F(0))-v
        p=q
    B=[sum(v*F(comb(k,r),comb(4,r))for r,v in p.items()if r<=k)for k in range(5)]
    return p,B
def cut_from_vector(group,weights,vector,kind):
    p,B=square_coefficients(vector,kind);expectation=sum(a*F(b)for a,b in zip(B,weights,strict=True));co={c:-v for c,v in zip(group['columns'],B,strict=True)if v};scale=max(map(abs,co.values()),default=F(0))
    if not scale:return dict(classification='UNRESOLVED_zero_polynomial')
    normalized={k:v/scale for k,v in co.items()};signature=json.dumps([(k,hex(v.numerator),hex(v.denominator))for k,v in sorted(normalized.items())],separators=(',',':'))
    return dict(classification='exact_violated_necessary_cone_plane'if expectation<0 else'UNRESOLVED_vector_not_strictly_separating',
                cone=kind,group=group,vector=[rec(v)for v in vector],power=[dict(degree=k,value=rec(v))for k,v in sorted(p.items())],
                coefficients=[dict(column=k,value=rec(v))for k,v in sorted(normalized.items())],bound=rec(0),
                exact_square_expectation=rec(expectation),normalized_violation=rec(-expectation/scale),cut_sha256=hashlib.sha256(signature.encode()).hexdigest(),
                mathematical_scope='Necessary conditional polynomial positivity, not observed source/force or a deterministic path')
def separate(group,x,emit):
    import numpy as np
    weights=[F(x[c])for c in group['columns']];y=moments(weights);records=[];cuts=[]
    emit(dict(kind='BEFORE_NEW_continuous_cone_group',group=group,actual_weights=[rec(v)for v in weights],moments=[rec(v)for v in y],
              zero_mass=y[0]==0,signed_mass=y[0]<0,zero_mass_other_moments_nonzero=y[0]==0 and any(y[1:]),no_clipping_or_normalization=True))
    for name,A in matrices(y).items():
        minors=principal_minors(A);exactPSD=all(dec(v['value'])>=0 for v in minors)
        record=dict(cone=name,matrix=[[rec(v)for v in r]for r in A],principal_minors=minors,exact_principal_minors_PSD=exactPSD)
        emit(dict(kind='AFTER_NEW_continuous_cone_principal_minors',group_id=group['id'],record=record))
        if not exactPSD:
            array=np.array(A,dtype=float)
            if not np.isfinite(array).all():raise ValueError('nonfinite cone matrix')
            emit(dict(kind='BEFORE_NEW_cone_eigendecomposition',group_id=group['id'],cone=name))
            values,vectors=np.linalg.eigh(array)
            emit(dict(kind='AFTER_NEW_cone_eigendecomposition_RETURN',group_id=group['id'],cone=name,eigenvalues=values,eigenvector=vectors[:,0]))
            vector=[F(float(v))for v in vectors[:,0]];cut=cut_from_vector(group,weights,vector,name)
            emit(dict(kind='AFTER_NEW_exact_cone_square_RETURN',group_id=group['id'],cut=cut));records.append(dict(group_id=group['id'],cone=name,classification=cut['classification']))
            if cut['classification']=='exact_violated_necessary_cone_plane':cuts.append(cut)
    return dict(all_exact_principal_minors_PSD=not records,cuts=cuts,unresolved_vectors=[v for v in records if v['classification']!='exact_violated_necessary_cone_plane'])
