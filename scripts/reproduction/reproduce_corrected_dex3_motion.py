"""Regenerate the bounded corrections from verified fitted inputs and profiles.

The source reconstruction and geometric fit searches are not rerun. Expected
generation reports bind the measured inputs; a new receipt identifies this
reproducer. A fresh continuous check is optional and requires the pinned Linux
geometry runtime. The simulator can be run with reproduce_frozen_dex3_replay.py.
"""

import argparse
import json
import os
import platform
import shutil
import subprocess
import sys
from pathlib import Path

from reproduce_frozen_dex3_replay import digest, restore_methods


def regenerate_stage(motion, profile, expected, output, producer_sha):
    import numpy as np
    from corrected_per_grasp_motion_v1 import load
    from corrected_per_grasp_motion_v5 import window_weight

    if not profile["static_original_surface_checks_passed"]:
        raise ValueError("The saved bounded fit was refused")
    side = ("left", "right").index(profile["side"])
    start, end = profile["time_start_s"], profile["time_end_s"]
    vector = np.asarray(profile["translation_amplitude_m"])
    if np.linalg.norm(vector) > 0.010:
        raise ValueError("Root correction exceeds the unchanged 10 mm budget")
    for phase in motion.sides[side]["phases"]:
        if not (end <= phase["interval"][0] or start >= phase["interval"][1]):
            raise ValueError("A noncontact repair overlaps an inferred grasp")
    times = np.unique(np.r_[motion.breakpoints, profile["constrained_timestamps_s"]])
    q, kinds, details = (
        np.asarray(values)
        for values in zip(*(motion.evaluate(float(t)) for t in times))
    )
    original_indices = np.searchsorted(times, motion.breakpoints)
    q[original_indices] = motion.knot_q
    kinds[original_indices] = motion.knot_kinds
    details[original_indices] = motion.knot_details
    weights = np.asarray([window_weight(float(t), start, end) for t in times])
    q[:, side, :3] += weights[:, None] * vector
    outside = (motion.breakpoints <= start) | (motion.breakpoints >= end)
    np.testing.assert_array_equal(q[original_indices[outside]], motion.knot_q[outside])
    data = load(motion._reproduction_input_path / "robot-motion-proposal.npz")
    before = data["robot_qpos_inferred"].copy()
    source_q = q[np.searchsorted(times, motion.times)]
    changed = np.any(source_q != before, axis=2)
    previous = data.get("robot_noncontact_surface_repair_inferred", False)
    data["robot_noncontact_surface_repair_inferred"] = previous | changed
    data["robot_qpos_inferred"] = source_q
    data["robot_transition_translation_delta_m"] += (
        source_q[:, :, :3] - before[:, :, :3]
    )
    anchors = data["robot_contact_intent_inferred"].any(axis=2)
    if data["robot_noncontact_surface_repair_inferred"][anchors].any():
        raise ValueError("A repair changed an inferred grasp anchor")
    np.testing.assert_array_equal(source_q[anchors], before[anchors])
    np.testing.assert_array_equal(source_q[:, :, 3:], before[:, :, 3:])
    output.mkdir()
    np.savez_compressed(output / "robot-motion-proposal.npz", **data)
    np.savez_compressed(
        output / "replay-knots.npz",
        timestamps_s=times,
        qpos_inferred=q,
        inference_kind=kinds,
        phase_details=details,
    )
    for filename, field in (
        ("robot-motion-proposal.npz", "payload_sha256"),
        ("replay-knots.npz", "replay_knots_sha256"),
    ):
        if digest(output / filename) != expected[field]:
            raise ValueError("Regenerated bytes differ: " + filename)
    report = dict(expected)
    report["generator_sha256"] = producer_sha
    report["reproduction_expected_generator_sha256"] = expected["generator_sha256"]
    report["reproduced_from_verified_fitted_profile"] = True
    report["locked_parent_report_sha256"] = digest(
        motion._reproduction_input_path / "report.json"
    )
    (output / "report.json").write_text(json.dumps(report, indent=2) + "\n")
    return data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--case", type=Path, required=True)
    parser.add_argument("--fitted-archive", type=Path, required=True)
    parser.add_argument("--supplement-archive", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--check-continuous", action="store_true")
    args = parser.parse_args()
    if args.out.exists():
        raise FileExistsError("Use a fresh output directory")
    if args.check_continuous and sys.platform != "linux":
        parser.error("Continuous checking requires the pinned Linux geometry runtime")
    snapshot = (
        Path(__file__).resolve().parents[2]
        / "docs/team/reproduction/dex3-motion-replay"
    )
    case = args.case.resolve()
    input_manifest = json.loads(
        (snapshot / "corrected-inputs-manifest-v1.json").read_text()
    )
    if (
        digest(case / "file-manifest.json")
        != input_manifest["case_file_manifest_sha256"]
    ):
        raise ValueError("Use the verified corrected simulator case")
    manifest = json.loads((case / "file-manifest.json").read_text())
    for name, expected in manifest["files_sha256"].items():
        if not (case / name).resolve().is_relative_to(case):
            raise ValueError("Case member leaves the restored directory")
        if digest(case / name) != expected:
            raise ValueError("Case hash mismatch: " + name)
    out = args.out.resolve()
    out.mkdir(parents=True)
    restore_methods(
        snapshot / "continuous-methods-v1.tar.gz",
        snapshot / "continuous-methods-manifest-v1.json",
        out / "methods",
    )
    restore_methods(
        args.fitted_archive,
        snapshot / "fitted-input-manifest.json",
        out / "inputs",
    )
    restore_methods(
        args.supplement_archive,
        snapshot / "corrected-inputs-manifest-v1.json",
        out / "supplement",
    )
    methods, inputs, supplement = out / "methods", out / "inputs", out / "supplement"
    shutil.copytree(
        supplement / "locked-gated-replay-motion-v2",
        inputs / "locked-gated-replay-motion-v2",
    )
    sys.path.insert(0, str(methods))
    import numpy as np
    from corrected_per_grasp_motion_v1 import load
    from locked_replay_motion_v2 import LockedReplayMotion as Original
    from locked_replay_motion_v3 import LockedReplayMotion as Corrected

    parameters = (
        case / "bundle",
        case / "retarget",
        inputs / "global-free-segment-motion-v3",
        inputs / "contact-interval-dense-full-chain-inputs-v1",
        inputs / "per-grasp-motion-atlas-reserve-v2.json",
    )
    source = case / "source/robotic_grounding"
    parent_path = inputs / "locked-gated-replay-motion-v2"
    parent = Original(*parameters, parent_path, source=source)
    parent._reproduction_input_path = parent_path
    original = load(parent_path / "robot-motion-proposal.npz")
    producer = digest(Path(__file__))
    for index, name in enumerate(
        ("locked-gated-replay-motion-v4", "locked-gated-replay-motion-v5"), 1
    ):
        profile = json.loads((supplement / f"profile-{index}.json").read_text())
        expected = json.loads(
            (supplement / f"expected-report-{index}.json").read_text()
        )
        measured_parent = (
            supplement / "locked-gated-replay-motion-v2/report.json"
            if index == 1
            else supplement / "expected-report-1.json"
        )
        if profile["parent_motion_report_sha256"] != digest(
            measured_parent
        ) or expected["locked_parent_report_sha256"] != digest(measured_parent):
            raise ValueError(
                "Saved fit and expected result have different measured parents"
            )
        target = inputs / name
        data = regenerate_stage(parent, profile, expected, target, producer)
        parent = Corrected(*parameters, target, source=source)
        parent._reproduction_input_path = target
        np.testing.assert_array_equal(
            np.asarray([parent.evaluate(float(t))[0] for t in parent.times]),
            data["robot_qpos_inferred"],
        )
    for key in original:
        if key not in ("robot_qpos_inferred", "robot_transition_translation_delta_m"):
            np.testing.assert_array_equal(original[key], data[key])
    delta = np.linalg.norm(
        data["robot_qpos_inferred"][:, :, :3]
        - original["robot_qpos_inferred"][:, :, :3],
        axis=2,
    )
    if delta.max() > 0.010 + 1e-10:
        raise ValueError("Total inferred correction exceeds 10 mm")
    expected_payload = load(case / "proposal/robot-motion-proposal.npz")
    if data.keys() != expected_payload.keys():
        raise ValueError("Output payload fields differ")
    for key in data:
        np.testing.assert_array_equal(data[key], expected_payload[key], err_msg=key)
    receipt = {
        "schema": "v2d.corrected-fitted-motion-reproduction.v1",
        "generator_sha256": producer,
        "runtime": {
            "platform": sys.platform,
            "python": platform.python_version(),
            "numpy": np.__version__,
        },
        "all_payload_arrays_identical": True,
        "array_count": len(data),
        "regenerated_payload_sha256": digest(target / "robot-motion-proposal.npz"),
        "regenerated_knots_sha256": digest(target / "replay-knots.npz"),
        "maximum_extra_source_root_correction_m": float(delta.max()),
        "all_original_observation_arrays_unchanged": True,
        "full_upstream_reconstruction_or_fit_search_rerun": False,
        "new_continuous_check_complete": False,
        "new_simulator_run": False,
        "physical_task_accepted": False,
    }
    (out / "reproduction-receipt.json").write_text(json.dumps(receipt, indent=2) + "\n")
    if args.check_continuous:
        command = [sys.executable, methods / "certify_locked_replay_scene_v11.py"]
        for name, value in zip(
            ("bundle", "baseline", "parent-proposal", "interval-inputs", "atlas"),
            parameters,
        ):
            command += ["--" + name, value]
        command += [
            "--source",
            source,
            "--proposal",
            target,
            "--material",
            supplement / "material",
            "--out",
            out / "continuous",
        ]
        subprocess.run(
            list(map(str, command)),
            check=True,
            env=dict(os.environ, OMP_NUM_THREADS="1", OPENBLAS_NUM_THREADS="1"),
        )
        checked = json.loads((out / "continuous/report.json").read_text())
        if not checked["complete_replay_object_self_and_cross_hand_surfaces_certified"]:
            raise ValueError("Fresh continuous model check refused the trajectory")
        receipt["new_continuous_check_complete"] = True
        (out / "reproduction-receipt.json").write_text(
            json.dumps(receipt, indent=2) + "\n"
        )
    print(json.dumps(receipt, indent=2))


if __name__ == "__main__":
    if not __debug__:
        raise RuntimeError("Do not disable the frozen method's invariant checks")
    main()
